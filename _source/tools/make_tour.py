"""Write js/tour.js: the four standing points and what can be clicked from each.
Directions are worked out from the camera positions Blender exported (renders/final/hotspots.json)."""
import json, math, sys
src, out = sys.argv[1], sys.argv[2]
P = json.load(open(src))["panoramas"]

def look(cam, p):
    R, L = cam["rotation_matrix"], cam["location"]
    d = [p[i] - L[i] for i in range(3)]
    col = lambda j: [R[0][j], R[1][j], R[2][j]]
    dot = lambda a, b: sum(x * y for x, y in zip(a, b))
    x, y, z = dot(d, col(0)), dot(d, col(1)), -dot(d, col(2))
    dist = math.sqrt(x * x + y * y + z * z)
    return round(math.degrees(math.atan2(x, z)), 2), round(math.degrees(math.asin(y / dist)), 2), round(dist, 2)

POINTS = [  # id, camera, name, file, short name for phones
    ("entrance", "Pano_01_Entrance", "By the door", "pano-01", "Door"),
    ("tables", "Pano_02_Mid", "At the tables", "pano-02", "Tables"),
    ("lamp", "Pano_03_Lamp", "By the lamp", "pano-03", "Lamp"),
    ("counter", "Pano_04_Barista", "Behind the counter", "pano-04", "Counter"),
]
CAM_KEY = {"entrance": "pano_01_entrance", "tables": "pano_02_mid", "lamp": "pano_03_lamp", "counter": "pano_04_barista"}

THINGS = {  # hotspot key in Blender -> what it opens
    "menu_new": "board:new", "menu_shakes": "board:shakes", "menu_icecream": "board:icecream",
    "menu_tea": "board:tea", "menu_coffee": "board:coffee",
    "wall_board_contact": "panel:contact", "wall_board_reviews": "panel:reviews",
    "about_us_plaque": "panel:about", "cups_shelf": "panel:merch",
    "dish_wraps": "dish:chicken-wrap", "dish_burgers": "dish:chicken-burger",
    "dish_paneer_sandwiches": "dish:paneer-sandwich", "dish_corn_sandwiches": "dish:corn-sandwich",
    "dish_chocolate_cake": "dish:chocolate-truffle", "dish_red_velvet": "dish:red-velvet",
    "dish_cheesecake": "dish:blueberry-cheesecake",
}
BOARDS = [k for k in THINGS if k.startswith("menu_")]
WALL = ["wall_board_contact", "wall_board_reviews"]
FRONT = ["about_us_plaque", "cups_shelf"] + [k for k in THINGS if k.startswith("dish_")]
SHOW = {   # what is worth clicking from each point (the food faces the customer side only)
    "entrance": BOARDS + WALL,
    "tables": BOARDS + WALL + FRONT,
    "lamp": BOARDS + WALL,
    "counter": BOARDS + WALL,
}
START = {"entrance": (0, -2), "tables": (0, -6), "lamp": (25, -4), "counter": (180, -10)}   # behind the counter you face the room

points = []
for pid, cam_name, name, file, short in POINTS:
    cam = P[cam_name]
    R = cam["rotation_matrix"]; fwd = (-R[0][2], -R[1][2])
    heading = round(math.degrees(math.atan2(fwd[0], fwd[1])), 2)
    pins = []
    for k in SHOW[pid]:
        yaw, pitch, dist = look(cam, cam["hotspots"][k])
        pins.append({"open": THINGS[k], "yaw": round(yaw + heading, 2), "pitch": pitch})
    steps = []
    for qid, qcam, qname, _, _s in POINTS:
        if qid == pid: continue
        loc = P[qcam]["location"]
        z = 1.2 if "counter" in (pid, qid) else 0.02      # a marker on the floor is hidden by the counter
        yaw, pitch, dist = look(cam, [loc[0], loc[1], z])
        steps.append({"to": qid, "label": qname, "yaw": round(yaw + heading, 2), "pitch": pitch, "dist": dist, "floor": z < 0.5})
    points.append({"id": pid, "name": name, "short": short, "image": "assets/pano/" + file + ".jpg", "small": "assets/pano/" + file + "-small.jpg",
                   "heading": heading, "start": {"yaw": START[pid][0], "pitch": START[pid][1]}, "pins": pins, "steps": steps})

js = ("/* Generated by _source/tools/make_tour.py from the Blender export. Angles are in degrees:\n"
      "   yaw 0 faces the counter, positive turns right; pitch positive looks up. */\n"
      "window.ELAICHI_TOUR = " + json.dumps({"points": points}, indent=1) + ";\n")
open(out, "w").write(js)
print("pins per point:", {p["id"]: len(p["pins"]) for p in points})
